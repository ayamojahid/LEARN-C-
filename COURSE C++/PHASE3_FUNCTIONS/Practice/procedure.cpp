// ## 1️⃣ Procedure

// Une procédure fait une action, mais **ne retourne pas de valeur**.

// ```cpp
#include <iostream>
using namespace std;

void afficherNom()
{
    cout << "Aya" << endl;
}

int main()
{
    afficherNom();

    return 0;
}
// ```

// ### Résultat

// ```text
// Aya
// ```

// 👉 `afficherNom()` affiche simplement le nom.

